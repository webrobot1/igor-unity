# Ведомая копия. Источник — /var/www/html/game/.claude/hooks/lib/mirror_copy.py в серверном
# репозитории; копию перезаписывает его хук при каждой правке источника. Правка копии теряется
# молча — вносить её в источник. Серверного репозитория нет под рукой → назвать нужную правку
# пользователю.

"""Пометка ВЕДОМОСТИ у копии свода либо скрипта — общий носитель хуков, которым нужно отличить
копию зеркала от собственного файла принимающей стороны.

Ставит пометку зеркалирование сводов (`client-skills-mirror.sh`), и другого признака авторства у
копии нет: ни имя, ни каталог владельца не называют — каталоги у адресата ОБЩИЕ с его собственными
файлами, а имя копии совпадает с именем источника. Читателей у признака двое, и вывод из него они
делают разный: зеркало снимает по нему выпавшую из множества копию, гейт владения путями
(`skill-guard.sh`) отбивает по нему правку копии. Разъехались бы копии признака молча — зеркало
перестало бы снимать своё либо гейт пропустил бы правку, которая теряется на следующей сверке, —
оттого признак живёт здесь одним экземпляром.

Своего набора самопроверки у модуля нет: обе стороны признака гоняются наборами вызывающих —
`client-skills-mirror.test.sh` (снятие выпавшей копии) и `skill-guard.test.sh` (отказ на правке
копии). Правится модуль — прогнать ОБА.
"""

import os

# Голова пометки: по ней копия и опознаётся. Полный текст пометки строит само зеркало — читателю
# признака нужна только голова.
MARK_HEAD = "Ведомая копия."

# Сколько строк головы файла читается в поисках пометки. Frontmatter свода бывает длиннее любого
# разумного среза по байтам, оттого граница считается строками.
HEAD_LINES = 200


def marked(path):
    """Стоит ли в файле пометка ведомости. Пометка встаёт первой непустой строкой ЗА головным
    блоком: за frontmatter у свода, за строкой `#!` у скрипта, а у модуля головного блока нет
    вовсе — она идёт первой строкой файла. Читается ровно голова: тело свода — сотни килобайт, и
    чтение его целиком легло бы на каждую сверку и на каждый перехваченный вызов. Frontmatter, не
    закрытый в пределах HEAD_LINES, отбивает файл как чужой: цена ошибки тут — снятый либо
    отбитый файл чужого репозитория."""
    try:
        with open(path, encoding="utf-8", errors="replace") as fh:
            line = fh.readline()
            if line.startswith("---"):
                for _ in range(HEAD_LINES):
                    line = fh.readline()
                    if not line:
                        return False
                    if line.startswith("---"):
                        break
                else:
                    return False
                line = fh.readline()
            elif line.startswith("#!"):
                line = fh.readline()

            for _ in range(HEAD_LINES):
                if not line:
                    return False
                if line.strip():
                    return MARK_HEAD in line
                line = fh.readline()
    except OSError:
        return False
    return False
