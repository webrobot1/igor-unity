#!/bin/bash

# Ведомая копия. Источник — /var/www/html/game/.claude/hooks/shared-orchestration-reminder.sh в
# серверном репозитории; копию перезаписывает его хук при каждой правке источника. Правка копии
# теряется молча — вносить её в источник. Серверного репозитория нет под рукой → назвать нужную
# правку пользователю.

# SessionStart hook: свод оркестрации адресован только тому, кто делегирует и говорит с
# пользователем, оттого из наследования CLAUDE.md он снят — правило его загрузки лежит в shared-core, а
# исполнение правила держится на внимании модели. Хук возвращает загрузке механику: предписание
# приходит отдельным сообщением на старте, мимо крупного свода shared-core.
# СОДЕРЖИМОЕ свода этим каналом не доставить: вывод хука режется на 10 000 символов (проверено
# прогоном — сверх лимита в контекст едет превью первых 2 КБ и путь к файлу), свод кратно больше
# порога уже сам по себе. Хук несёт МОМЕНТ и КАНАЛ загрузки, не текст правил: копия расходилась бы
# с владельцем молча. Канал назван вызовом, адрес файла — запасным путём на случай, когда имя не
# резолвится: `Skill()` отдаёт тело целиком одним ответом, файловое чтение свода такого объёма
# распадается на страницы (проверено вызовом).
# Адресность держится двумя фактами, оба проверены прогоном: событие наступает только у главной
# сессии (у субагента — своё, SubagentStart), а запуск сессии агентом (`--agent`) виден по
# непустому agent_type. Исполнителю свод не нужен — ради этого он из наследования и снят.
# Тем же каналом идут своды правил кода (`shared-code`, свод языка, свод фреймворка, `implement-app`): с
# наследования CLAUDE.md они сняты ради исполнителей без кода (текстовому агенту они клали в контекст
# лишние 130 КБ), а пишущий код исполнитель получает их через `skills:` своей шапки. Какие из них
# назвать, решает НАЛИЧИЕ файла свода: хук общий проектам с разным фреймворком и бывает зеркалирован
# в другие контуры, где набор сводов свой, — перечень в теле хука разошёлся бы с ним молча.
# У ветви сжатия предмет ВТОРОЙ: сжатие переписывает контекст сводкой, и незакрытая работа доезжает
# дальше только планом. Момент тут же — первый ход после сжатия: план своей работы сверяется с
# остатком из сводки по составу, дописывается только недостающее (shared-plan-lifecycle, абзац о передаче
# работы дальше); состав сводки под сохранение остатка и путь к плану задаёт shared-precompact-remainder.sh
# на самом сжатии.
# Исключение из «момента и канала»: ветвь старта несёт и текст одного правила — первый ответ называет имя
# сессии для сообщений других сессий (shared-orchestration «Манера общения»); строка короткая, осознанный
# дубль, правится парно.
# Третий предмет ветви сжатия — копии сводов: программа возвращает вызванные своды вложением, длинный
# обрезав, а сверх бюджета выкинув целиком, и обрезанная копия выглядит загруженной. Хук называет своды,
# чья копия после сжатия не целая, по правилу программы, повторённому в lib/shared_transcript.py.

input=$(cat)

read -r agent source <<< "$(python3 -c '
import sys, json
try:
    d = json.loads(sys.stdin.read())
except Exception:
    sys.exit(0)
print((d.get("agent_type") or "-"), (d.get("source") or "-"))' <<< "$input" 2>/dev/null)"

# Разбор не удался — вывод пуст: адресат неизвестен, напоминание не выдаётся. Ложный инжект
# исполнителю дороже пропущенного напоминания: свод в его контексте паразитный.
[ -n "$agent" ] || exit 0
[ "$agent" = "-" ] || exit 0

proj="$(cd "$(dirname "$0")/../.." 2>/dev/null && pwd)"
[ -n "$proj" ] || exit 0
skill="$proj/.claude/skills/shared-orchestration/SKILL.md"
[ -f "$skill" ] || exit 0

# Своды правил кода — по наличию файла свода: имя, которого у проекта либо контура нет, отсеивается.
code_line=""
code_names=""
for name in shared-code shared-php implement-platform implement-app; do
  file="$proj/.claude/skills/$name/SKILL.md"
  [ -f "$file" ] || continue
  code_line="$code_line Skill('$name'), при «Unknown skill» — Read $file;"
  code_names="$code_names $name"
done
[ -n "$code_line" ] && code_line=" Правила кода — тем же ходом:${code_line%;}. Наследованием они не идут: исполнителю без кода лишние."

if [ "$source" = "compact" ]; then
  # Копии сводов после сжатия (lib/shared_transcript.py skills_cut_by_compaction): свод оркестрации и
  # своды кода названы своими строками, прочие обрезанные и выпавшие — перечнем. Транскрипт не прочитан
  # либо разбор упал — строк нет, и свод оркестрации идёт прежней проверкой «лежит ли он в контексте».
  # Текст ветви — о выборе продолжения и о сводах, оставленных сжатием не целиком, — осознанный дубль
  # `shared-orchestration` «Длинная сессия деградирует», правится парно.
  states=$(HOOKS_DIR="$proj/.claude/hooks" SKIP_NAMES="shared-orchestration$code_names" python3 -c '
import json, os, sys
sys.path.insert(0, os.path.join(os.environ["HOOKS_DIR"], "lib"))
from shared_transcript import caller_transcript, skills_cut_by_compaction
event = json.loads(sys.stdin.read())
path = caller_transcript(event)
states = skills_cut_by_compaction(path) if path else None
if states is None:
    sys.exit(0)
skip = os.environ["SKIP_NAMES"].split()
print("ORCH\t" + dict(states).get("shared-orchestration", "в этой сессии не загружался"))
print("LOST\t" + ", ".join("%s (%s)" % (n, s) for n, s in states if s != "целиком" and n not in skip))' <<< "$input" 2>/dev/null)
  orch_state=$(printf '%s\n' "$states" | sed -n 's/^ORCH\t//p')
  lost=$(printf '%s\n' "$states" | sed -n 's/^LOST\t//p')

  if [ -z "$orch_state" ]; then
    orch_line="Контекст сжат: свод оркестрации мог выпасть. Прежде чем запускать исполнителя и прежде чем отвечать пользователю — проверить, лежит ли он в контексте, и при отсутствии загрузить целиком: Skill('shared-orchestration'), при «Unknown skill» — Read $skill."
  elif [ "$orch_state" = "целиком" ]; then
    orch_line="Контекст сжат: свод оркестрации лежит в контексте целиком."
  else
    orch_line="Контекст сжат, свод оркестрации $orch_state. Прежде чем запускать исполнителя и прежде чем отвечать пользователю — загрузить целиком: Skill('shared-orchestration'), при «Unknown skill» — Read $skill."
  fi
  lost_line=""
  [ -n "$lost" ] && lost_line=" Своды, загруженные сессией, сжатие оставило в контексте не целиком: $lost. Каждый загрузить заново целиком, Skill(<имя>), до первого действия в его домене: обрезанная копия и сводка сжатия всех его правил не несут."

  echo "$orch_line$lost_line$code_line Работа не закрыта — сверить план своей работы с остатком из сводки по составу, дописать только недостающее и назвать пользователю путь к файлу плана; плана нет — завести. На ближайшей контрольной точке вынести окном выбор продолжения: новая сессия по плану либо продолжение в этой (shared-orchestration «Длинная сессия деградирует»). Работа исчерпана, остатка нет → окно не выносится: ответ заканчивается строкой, что новую задачу лучше начать в новой сессии."
else
  # Строка об имени сессии — осознанный дубль `shared-orchestration` «Манера общения», правится парно.
  echo "Прежде чем запускать исполнителя и прежде чем отвечать пользователю — загрузить целиком свод оркестрации: Skill('shared-orchestration'), при «Unknown skill» — Read $skill. Наследованием CLAUDE.md свод не доезжает: адресован только тому, кто делегирует и говорит с пользователем.$code_line Первый ответ пользователю называет короткое имя сессии, по которому ей пишут другие сессии: его отдаёт ListAgents строкой «This session is …»; ID сессии и его начальные символы адресом сообщения не служат."
fi
