#!/bin/bash

# Ведомая копия. Источник — /var/www/html/game/.claude/tools/shared-fetch-page.sh в серверном
# репозитории; копию перезаписывает его хук при каждой правке источника. Правка копии теряется
# молча — вносить её в источник. Серверного репозитория нет под рукой → назвать нужную правку
# пользователю.

# Загрузка внешней страницы её разметкой в файл — канал чтения состава страницы целиком.
#
# Повод: штатное чтение веб-страницы отдаёт пересказ другой моделью, а он теряет встроенные элементы
# (проигрыватель, карточку сервиса) и хвост длинного текста, оставаясь на вид полным ответом. Состав
# страницы и отрицание о нём строятся только по самой разметке (shared-core «Локатор ≠ доказательство»).
#
# Печатает путь, размер и число строк: дальше файл читается файловым тулом окнами до конца и ищется
# грепом. Тело страницы в вывод не идёт — оно на порядок больше окна ответа команды.
#
# Место по умолчанию — каталог инструмента проекта: файл живёт до конца своего шага
# (shared-core «Место файла, заведённого по ходу работы»). Снимает его тот же проход.
#
# Использование:
#   bash <корень проекта>/.claude/tools/shared-fetch-page.sh <url> [путь файла]
#
# Страница, чьё содержимое рисует скрипт, этим каналом приходит пустой оболочкой — её читают браузером.

set -u

url="${1:-}"
dest="${2:-}"

if [ -z "$url" ]; then
  echo "нужен адрес страницы: shared-fetch-page.sh <url> [путь файла]" >&2
  exit 2
fi

case "$url" in
  http://*|https://*) ;;
  *) echo "адрес начинается с http:// либо https://: $url" >&2; exit 2 ;;
esac

if [ -z "$dest" ]; then
  root="$(cd "$(dirname "$0")/../.." 2>/dev/null && pwd)"
  [ -n "$root" ] || { echo "не найден корень проекта от $0" >&2; exit 1; }
  host=$(printf '%s' "$url" | sed -e 's#^[a-z]*://##' -e 's#[/?].*$##' -e 's#[^A-Za-z0-9.-]#-#g')
  mkdir -p "$root/.playwright-mcp" || exit 1
  # Номер процесса в имени: два вызова на один хост в одну секунду (параллельные исполнители) иначе
  # пишут в один файл, и второй молча перезаписывает первый.
  dest="$root/.playwright-mcp/page-${host}-$(date +%Y%m%d-%H%M%S)-$$.html"
fi

# Отказ загрузки — отказ команды: код ответа сервера уходит в сообщение, файл-огрызок не остаётся.
code=$(curl -sS -L --max-time 60 --max-filesize 20971520 \
  -A "Mozilla/5.0 (compatible; claude-code)" \
  -o "$dest" -w '%{http_code}' "$url") || {
    rm -f "$dest"
    echo "загрузка не удалась: $url" >&2
    exit 1
  }

if [ "$code" -lt 200 ] || [ "$code" -ge 400 ]; then
  rm -f "$dest"
  echo "сервер ответил $code: $url" >&2
  exit 1
fi

printf 'файл: %s\nкод ответа: %s\nбайт: %s\nстрок: %s\n' \
  "$dest" "$code" "$(wc -c < "$dest")" "$(wc -l < "$dest")"
