#!/bin/bash

# Ведомая копия. Источник — /var/www/html/game/.claude/tools/shared-verify-edit.sh в серверном
# репозитории; копию перезаписывает его хук при каждой правке источника. Правка копии теряется
# молча — вносить её в источник. Серверного репозитория нет под рукой → назвать нужную правку
# пользователю.

# Приёмка правки текстового носителя: легло ли заказанное и не легло ли ДВАЖДЫ.
# Ответ идёт числами — читателю нужен состав легшего, не текст файла
# (shared-core «Модальность потребителя канала»), а перечитывание файла двойную
# вставку ловит не лучше счёта вхождений и стоит дороже.
# Точка применения — приёмка координатором и повтор задания после обрыва хода:
# оборвавшийся исполнитель себя не проверит, а повтор поверх легшей правки
# кладёт вторую копию (shared-orchestration, абзац об отмене агента).
#
# Использование: shared-verify-edit.sh <абсолютный-путь> <фраза> [фраза...]
# Код возврата: 0 — каждая фраза встретилась РОВНО один раз; 1 — иначе.

set -u

if [ $# -lt 2 ]; then
    echo "использование: $0 <абсолютный-путь> <фраза> [фраза...]" >&2
    exit 2
fi

file=$1
shift

case "$file" in
    /*) ;;
    # Относительный путь разрешается рабочей директорией вызывающего, а она
    # живёт между вызовами и сдвигается чужой командой (shared-core, адресация путей).
    *) echo "путь должен быть абсолютным: $file" >&2; exit 2 ;;
esac

[ -f "$file" ] || { echo "файла нет: $file" >&2; exit 2; }

status=0

for phrase in "$@"; do
    # Ведущий «!» — ожидание ОТСУТСТВИЯ: вырез закрытого пункта принимается тем
    # же вызовом, что и вставка нового (shared-plan-lifecycle: закрытое уходит целиком).
    want_gone=0
    case "$phrase" in
        '!'*) want_gone=1; phrase=${phrase#!} ;;
    esac

    # -o, не -c: своды пишутся длинными строками (абзац = строка), и счёт
    # СТРОК показал бы 1 там, где вставка легла дважды в один абзац.
    count=$(grep -oF -- "$phrase" "$file" | wc -l)

    if [ "$want_gone" = 1 ]; then
        case "$count" in
            0) verdict="ок" ;;
            *) verdict="ОСТАЛОСЬ"; status=1 ;;
        esac
    else
        case "$count" in
            1) verdict="ок" ;;
            0) verdict="НЕ ЛЕГЛО"; status=1 ;;
            *) verdict="ДУБЛЬ"; status=1 ;;
        esac
    fi

    printf '%-9s %2s  %s\n' "$verdict" "$count" "$phrase"
done

# Дифф — вторая половина ответа: показывает объём легшего, включая куски,
# чьих фраз вызывающий не назвал. Файл вне git — строки просто нет.
if git -C "$(dirname "$file")" rev-parse --git-dir >/dev/null 2>&1; then
    stat=$(git -C "$(dirname "$file")" diff --stat -- "$file" | tail -1)
    [ -n "$stat" ] && echo "дифф:${stat}"
fi

exit $status
