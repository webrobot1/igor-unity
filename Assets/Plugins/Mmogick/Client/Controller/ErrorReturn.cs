using UnityEngine;

namespace Mmogick
{
	/// <summary>
	/// Разбор очереди ошибок отдельным компонентом на объекте контроллера. Исключение в Awake любого звена
	/// цепочки контроллеров движок встречает выключением всего компонента-контроллера: его Update и LateUpdate
	/// больше не идут, ошибку в очереди разобрать некому, и вход застывает под панелью загрузки. Соседний
	/// компонент того же объекта это исключение не выключает.
	///
	/// Разбирает в LateUpdate: движок зовёт его отдельно от Update, и звено, чьё тело бросает раньше своего
	/// base.Update(), разбор не отменяет. Разбор в <see cref="ConnectController"/>.Update остаётся: ошибку,
	/// пришедшую между кадрами, он снимает до шага корутин кадра — те разбирали бы карты поверх неё.
	///
	/// Возврат на экран входа идёт корутиной самого контроллера: у выключенного компонента активного объекта
	/// корутина стартует и идёт кадр за кадром.
	/// </summary>
	public class ErrorReturn : MonoBehaviour
	{
		[SerializeField]
		private ConnectController controller;

		private void Awake()
		{
			if (controller == null)
			{
				// Компонент снимаем сами: Error уводит игрока на экран входа разбором в Update контроллера, но
				// исполнение продолжается, и LateUpdate успел бы обратиться к неприсвоенной ссылке.
				enabled = false;
				ConnectController.Error("не присвоен контроллер разбору очереди ошибок");
				return;
			}
		}

		private void LateUpdate()
		{
			controller.LeaveIfErrors();
		}
	}
}
