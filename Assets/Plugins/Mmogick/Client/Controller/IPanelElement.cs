namespace Mmogick
{
    /// <summary>
    /// Элемент панели интерфейса, адресуемый парой «слово панели + ключ». Слово называет панель: у
    /// панели, показывающей компонент существа, это slug компонента; у окна без такого компонента —
    /// слово, объявленное самим элементом. Ключ — то, что элемент показывает и чем шлёт команду
    /// (номер слота, код заклинания, код слота экипировки), всегда строкой: число — его десятичной
    /// записью. Имя объекта сцены адресом не служит: его задаёт вёрстка, и с тем, что элемент
    /// показывает, оно расходится.
    ///
    /// Читает пару оснастка съёмки роликов (Assets/Plugins/Mmogick/VideoRig): сценарий целится в элемент
    /// по ней, а не по объекту сцены. Контракт лежит в платформенной сборке — единственной, которую
    /// видят и реализации в коде игры, и оснастка. С сервером слова и ключи кодом не согласуются:
    /// словарь задаёт документ сценария, элементы его объявляют.
    /// </summary>
    public interface IPanelElement
    {
        /// <summary>Слово панели.</summary>
        string Panel { get; }

        /// <summary>Ключ элемента строкой.</summary>
        string Key { get; }
    }
}
