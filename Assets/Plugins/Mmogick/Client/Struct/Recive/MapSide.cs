namespace Mmogick
{
	/// <summary>
	/// Соседняя карта, примыкающая к текущей в открытом мире. x/y — смещение её левого-верхнего угла
	/// относительно текущей карты в тайлах: знак задаёт сторону (y&gt;0 — сверху, y&lt;0 — снизу,
	/// x&gt;0 — справа, x&lt;0 — слева), у самой текущей карты смещение нулевое.
	/// </summary>
	[System.Serializable]
	public class MapSide
	{
		/// <summary>
		/// Имя соседней локации — показывается в отладочном окне рядом с номером карты.
		/// </summary>
		public string name;

		public float x;
		public float y;

		/// <summary>
		/// Габариты соседа в тайлах: ими считается, попадает ли точка в его границы при склейке.
		/// </summary>
		public float width;
		public float height;

		/// <summary>
		/// Доступность локации: true — сосед отозвался, false — его запуск отказывает. Поля НЕТ вовсе, пока
		/// сервер соседей не опрашивал (первые мгновения после старта карты) — ответа о них ещё не существует.
		/// Отсутствие каждый читатель трактует по своей цене ошибки: движение считает такую карту непроходимой
		/// (уйти туда — остаться записанным на карту, в которую не войти), а метка поломки на проходе ставится
		/// только по явному false, иначе она мигала бы на каждом старте.
		/// </summary>
		public bool? ready;

		new public string ToString()
		{
			return x + "," + y;
		}
	}
}
