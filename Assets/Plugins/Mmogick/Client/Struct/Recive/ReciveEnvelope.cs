namespace Mmogick
{
    /// <summary>
    /// Служебные поля пакета сервера без самого мира: ошибка, смена хоста при переходе, действие пакета,
    /// метка времени для расчёта пинга.
    ///
    /// Нужен сетевому потоку: он принимает пакет и обязан сразу увидеть ошибку, переход на другой сервер и
    /// метку времени, но разбирать мир ему нельзя — мир разбирает главный поток, и в свой, более конкретный
    /// тип (у контроллера игрока он богаче базового). Разбор всего пакета в обоих местах означал бы сборку
    /// сотен объектов сущностей дважды на каждый кадр.
    ///
    /// Поля-имена обязаны совпадать с <see cref="Recive{P, E}"/> — это один и тот же пакет, прочитанный
    /// на разную глубину.
    /// </summary>
    [System.Serializable]
    public class ReciveEnvelope
    {
        public long unixtime;

        public string error;

        public string action;

        public string host;

        public string token;
    }
}
