namespace Mmogick
{
    /// <summary>
    /// Служебные поля пакета сервера без самого мира: ошибка, смена карты, действие пакета, метка времени
    /// для расчёта пинга.
    ///
    /// Нужен сетевому потоку: он принимает пакет и обязан сразу увидеть ошибку, переход на другой сервер и
    /// метку времени, но разбирать мир ему нельзя — мир разбирает главный поток, и в свой, более конкретный
    /// тип (у контроллера игрока он богаче базового). Разбор всего пакета в обоих местах означал бы сборку
    /// сотен объектов сущностей дважды на каждый кадр.
    ///
    /// Полный пакет (<see cref="Recive{P, E}"/>) наследует эти поля, а не повторяет: это один и тот же пакет,
    /// прочитанный на разную глубину, и имена его служебных полей заданы здесь одним списком.
    /// </summary>
    [System.Serializable]
    public class ReciveEnvelope
    {
        public long unixtime;

        public string error;

        public string action;

        /// <summary>
        /// карта перезагружается: сервер шлёт это перед остановкой песочницы и на несколько секунд перестаёт
        /// читать соединение. Клиент ставит отправку команд на паузу, показывает игроку надпись и не считает
        /// пингом замер, снятый на этом окне. Снимает состояние пришедший следом полный мир (action = load).
        /// </summary>
        public bool reloading;

        /// <summary>
        /// адрес сервера новой карты при переходе на смежную поднятую — по нему клиент переподключается напрямую
        /// </summary>
        public string host;

        /// <summary>
        /// токен для авторизации на новом сервере при смене карты (приходит вместе с host)
        /// </summary>
        public string token;

        /// <summary>
        /// карта, на которую сервер перевёл нашего игрока, когда своего адреса у неё тут нет (интерьер,
        /// дальняя карта, ещё не поднятая соседняя): заходим на неё заново через авторизацию — она же
        /// эту карту и поднимает. Приходит вместо host/token.
        /// </summary>
        public int? map;
    }
}
