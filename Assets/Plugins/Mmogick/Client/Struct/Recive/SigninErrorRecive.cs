namespace Mmogick
{
	/// <summary>
	/// Отказ сервера на вход либо регистрацию. Приходит вместо пакета входа и своим кодом ответа (не 2xx):
	/// неверный логин, слишком частые входы, поднимающийся сервер карты, непрошедший проверку ввод.
	///
	/// Отдельная структура, а не поля в SigninRecive: тела успеха и отказа не пересекаются вовсе, а разбор
	/// серверного пакета строгий (см. BaseController) — лишнее поле роняет разбор целиком, потому отказ и
	/// разбирается своей структурой, выбираемой по коду ответа.
	/// </summary>
	[System.Serializable]
	public class SigninErrorRecive
	{
		/// <summary>
		/// Текст отказа для игрока. Приходит у каждого отказа; у непрошедшего проверку ввода несёт первое
		/// нарушение из violations.
		/// </summary>
		public string error = "";

		/// <summary>
		/// Разбор отказа по полям ввода: поле запроса → сообщение о нарушении. Приходит только у проверки
		/// ввода, у прочих отказов поля нет вовсе.
		/// </summary>
		public System.Collections.Generic.Dictionary<string, string> violations;

		/// <summary>
		/// Через сколько секунд повторить вход. Приходит с ошибкой, означающей ПОВТОРИМЫЙ отказ: сервер карты
		/// ещё поднимается (холодный старт грузит весь мир карты и длится десятки секунд). Ждать этого в самом
		/// запросе сервер не может — рабочих процессов у него единицы, и занятые ожиданием они кладут вместе с
		/// игрой всё остальное. Поэтому ожидание живёт здесь: пауза и повторный вход, игроку ошибку не
		/// показываем. 0 — отказ окончательный, показываем error как есть.
		/// </summary>
		public int retry = 0;
	}
}
