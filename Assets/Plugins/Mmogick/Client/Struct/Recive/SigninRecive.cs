namespace Mmogick
{
	/// <summary>
	/// Структура полученных данных при авторизации
	/// </summary>
	[System.Serializable]
	public class SigninRecive
	{
		public string host;

		public string key;
		public string token;

		public float step;
		public int fps;

		public int map;
		public int game;

		// Мир текущей карты и его название. Кеш карт общий на игру, карты разных миров лежат в нём вперемешку,
		// а координаты открытого мира у каждого мира свои — обзорная карта строится по картам кеша с этим
		// миром. Смена значения означает уход в другой мир (интерьер, подземелье): прежняя раскладка не
		// продолжается. Название — подпись обзорной карты, справочника миров у клиента нет.
		public int world;
		public string world_name;

		public int position_precision;

		// Геометрия упора в преграду, которой сервер считает шаг существа (move/walk/index):
		// creep_depth — насколько глубоко упёршийся заходит в свою клетку (доля клетки от её центра в сторону
		// преграды), corner_offset — длина диагонального пробника обхода угла (доля клетки по каждой оси от
		// собственной позиции). Величины задаёт ИГРА, у каждой свои — клиенту хардкодить их нечем, а без них
		// он не повторит серверный расчёт шага и не отличит глухой упор от места, где обход ещё возможен.
		// По контракту оба поля приходят ВСЕГДА и строго больше нуля — default'а здесь намеренно нет,
		// пропущенное либо неположительное значение = нарушение контракта. Проверка — в SigninController.
		public float creep_depth;
		public float corner_offset;

		// Радиус (в клетках), в котором сервер ищет проходимую клетку вокруг непроходимой цели движения. Им
		// клиент решает, есть ли смысл слать команду вовсе: свой, меньший, отбрасывал бы клики, которые сервер
		// исполнил бы. По контракту приходит всегда и строго больше нуля.
		public int passable_search_radius;

		// Имя action, обозначающего «idle» (сущность в покое). Клиент переводит им тело в покой по таймауту
		// неактивности (ObjectModel.Update).
		// Сервер шлёт это поле под именем "idle" (не "idle_action") — замапливаем через JsonProperty,
		// чтобы локальное имя оставалось семантически понятным (не "idle", которое сбивало бы:
		// "флаг покоя?" vs "имя action-а"). По контракту поле шлётся ВСЕГДА и имеет непустое значение —
		// default'а здесь намеренно нет, пропущенное/пустое поле = нарушение контракта: подставленный дефолт
		// спрятал бы ошибку сервера (skill code «Отказ и дефолт»). Проверка — в SigninController.
		[Newtonsoft.Json.JsonProperty("idle")]
		public string idle_action;

		// Game-level справочник всех slot-slug-ов экипировки разрешённых в этой игре (head/chest/hand_r/...).
		// Подмножество User.equipmentSlot, выбранное в админке. Значение Dictionary всегда true — формат
		// (slug → true) выбран чтобы Newtonsoft не путал с массивом при сериализации.
		// Применение: рисование ячеек инвентаря; валидация что prefab.equipable_slot (из /prefabs)
		// и слот якоря (из object_slot пакета скелета) лежат в этом наборе.
		public System.Collections.Generic.Dictionary<string, bool> equipment_slot;

		// Класс объектов карты, которыми задан переход на другую карту (значение поля type у объекта слоя
		// либо class у самого слоя). Клиенту нужен, чтобы отметить такие места свечением: сущности под
		// переходом нет, его исполняет сама разметка. Пусто — игра переходами по разметке не пользуется.
		public string warp;

		// Полей отказа тут нет: отказ сервер отдаёт кодом ответа не 2xx и своим телом (SigninErrorRecive).
		// Поле отказа в этой структуре значило бы, что его несёт успешный пакет, — таким он не приходит вовсе,
		// а лишнее объявленное поле маскировало бы разбор отказа под удавшийся вход.
	}
}
