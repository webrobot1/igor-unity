namespace Mmogick
{
    /// <summary>
    /// Элемент интерфейса, который нажатие берёт «в руку» — переносит на курсор: карточка книги
    /// заклинаний, ячейка инвентаря, ячейка экипировки, позиция чужого контейнера. По этому признаку
    /// <see cref="CursorController"/> и меняет форму указателя, поэтому отвечать он обязан ровно то же,
    /// что решит нажатие: рука над тем, что нажатием не берётся, обещает несбыточное.
    /// </summary>
    public interface ITakeable
    {
        /// <summary>Возьмёт ли нажатие прямо сейчас: хватает ли маны, прошёл ли откат, свободен ли курсор.</summary>
        bool CanTake { get; }
    }
}
