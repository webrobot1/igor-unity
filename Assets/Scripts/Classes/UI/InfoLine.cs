using System;

namespace Mmogick
{
    /// <summary>
    /// Откуда берётся значение строки окна сведений.
    /// </summary>
    public enum InfoSource
    {
        /// <summary>
        /// Свойство существа: значение спрашивают у него самого, а чего он о себе не рассказал — у
        /// каталога префабов, где лежит типовое для вида.
        /// </summary>
        Component,

        /// <summary>
        /// Команда, висящая на существе: значение — её таймаут, то есть как часто она повторяется.
        /// Типового значения у команды нет — пока команда на существе не висела, показывать нечего
        /// (см. EntityModel.HasEvent). Так придут строки восстановления здоровья и маны.
        /// </summary>
        Command
    }

    /// <summary>
    /// Одна строка окна сведений о существе: откуда взять значение, как его назвать и как показать.
    /// Перечень таких строк — единственное место, которое правят, добавляя новое свойство: показ
    /// перебирает перечень и о самих свойствах ничего не знает.
    /// </summary>
    public class InfoLine
    {
        /// <summary>Откуда берётся значение.</summary>
        public readonly InfoSource Source;

        /// <summary>Slug компонента либо имя группы команды — смотря что <see cref="Source"/>.</summary>
        public readonly string Key;

        /// <summary>
        /// Ключ второго числа строки, если оно есть: у свойства — компонент запаса («текущее из
        /// максимума»), у команды — имя её данных, которыми она распоряжается («столько-то за раз»).
        /// null — число одно. Читается тем же источником, что и <see cref="Key"/>, и приходит в
        /// <see cref="Format"/> вторым доводом; нет второго числа — там придёт null.
        /// </summary>
        public readonly string PairKey;

        /// <summary>
        /// Подпись величины («Здоровье»). null — строка сама себе фраза: <see cref="Format"/> вернёт её
        /// целиком, как в блоке особенностей, где о существе рассказывают, а не перечисляют числа.
        /// </summary>
        public readonly string Title;

        /// <summary>
        /// Как показать значение: число, доля, расстояние, срок. Второй довод — второе число строки
        /// (см. <see cref="PairKey"/>), null — его нет.
        /// </summary>
        public readonly Func<float, float?, string> Format;

        /// <summary>
        /// Второе число строки, снятое с самого существа — не с его свойств и не с данных команды:
        /// скорость, которой оно при нас ходило. Второй источник для того же места, что и
        /// <see cref="PairKey"/>, поэтому задают что-то одно. null — снимать нечего; null в ответе —
        /// существо нужного при нас не делало.
        /// </summary>
        public readonly Func<ObjectModel, float?> Observed;

        /// <summary>
        /// Показывать только присланное про ЭТО существо, без падения на типовое значение вида. Ставят
        /// свойству, которое сервер намеренно держит при себе: у него есть умолчание в справочнике, и
        /// без запрета окно показало бы это умолчание как сведения о существе — «мана 5 / 5» у того,
        /// чью ману нам знать не полагается. Свойство перестанут скрывать — строка оживёт сама, менять
        /// тут будет нечего.
        /// </summary>
        public readonly bool OwnOnly;

        /// <summary>
        /// Компонент, чей значок стоит у строки, когда сама строка про другое: восстановление здоровья
        /// показывает сердце, восстановление маны — жемчужину, хотя значение обеим даёт команда. null —
        /// строка берёт значок у своего же компонента, а строке команды значка тогда не полагается вовсе.
        /// Взятый значок называет ЧТО прибывает, подсказка же остаётся о самой строке: описание чужого
        /// компонента объясняло бы запас, а не его восстановление.
        /// </summary>
        public readonly string IconKey;

        public InfoLine(
            string key,
            string title,
            Func<float, float?, string> format,
            string pairKey = null,
            InfoSource source = InfoSource.Component,
            Func<ObjectModel, float?> observed = null,
            bool ownOnly = false,
            string iconKey = null)
        {
            Source = source;
            Key = key;
            Title = title;
            Format = format;
            PairKey = pairKey;
            Observed = observed;
            OwnOnly = ownOnly;
            IconKey = iconKey;
        }
    }
}
