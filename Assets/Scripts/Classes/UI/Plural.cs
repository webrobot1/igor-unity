namespace Mmogick
{
    /// <summary>
    /// Согласование существительного с числом по-русски: «1 монета», «2 монеты», «5 монет».
    /// Единственное место, где живёт само правило, — вызывающему остаётся назвать три словоформы.
    ///
    /// Носитель нужен потому, что правило одно, а мест, где оно требуется, много: сроки, расстояния,
    /// деньги, количества. Разложенное по этим местам, оно копируется телом целиком (тринадцать строк
    /// на каждую пару слов) и расходится молча — ошибку в одной копии не видно ни компилятору, ни тестам,
    /// а игроку видно сразу.
    /// </summary>
    public static class Plural
    {
        /// <summary>
        /// Число с согласованным словом: <paramref name="one"/> — форма при единице («клетка»),
        /// <paramref name="few"/> — при двух-четырёх («клетки»), <paramref name="many"/> — при
        /// остальных («клеток»).
        ///
        /// Дробное значение всегда берёт форму «few»: «2,5 клетки», «1,5 минуты» — счётной единицы
        /// у дроби нет, и правило целых к ней не применяется.
        /// Одиннадцать-четырнадцать — исключение русского счёта: они берут «many» вопреки последней
        /// цифре («11 клеток», не «11 клетка»).
        /// </summary>
        public static string Of(float value, string one, string few, string many)
        {
            // Целое показываем без хвоста, дробное — с сотыми: тот же вид числа, что у прочих величин
            // интерфейса.
            string count = value.ToString("0.##");

            if (value != UnityEngine.Mathf.Floor(value))
                return count + " " + few;

            int tail = UnityEngine.Mathf.Abs(UnityEngine.Mathf.RoundToInt(value)) % 100;

            if (tail >= 11 && tail <= 14)
                return count + " " + many;

            switch (tail % 10)
            {
                case 1: return count + " " + one;
                case 2:
                case 3:
                case 4: return count + " " + few;
                default: return count + " " + many;
            }
        }
    }
}
