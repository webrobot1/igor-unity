using UnityEngine;
using UnityEngine.UI;

namespace Mmogick
{
    /// <summary>
    /// Контур надписи интерфейса. Толщину задаёт сам компонент — в сцене и в префабе его только вешают.
    ///
    /// Единый носитель нужен потому, что контур настраивался руками у каждой надписи и разъехался: на
    /// одном и том же виде текста стояли и разные сдвиги, и три разные прозрачности чёрного, а разницу
    /// между ними никто не задумывал — её просто некому было держать.
    ///
    /// Толщина — РОВНО ОДИН ЭКРАННЫЙ ПИКСЕЛЬ, и это не вкусовая величина, а единственная работающая.
    /// Контур рисуется четырьмя копиями букв со сдвигом: сдвиг меньше пикселя размазывает копии по
    /// соседним точкам экрана, буквы теряют края и сливаются с фоном; сдвиг больше пикселя разносит
    /// копии настолько, что они читаются грязью вокруг текста, а мелкие буквы съедает вовсе. Надписи
    /// набраны кеглем от 15 до 110 в по-разному сжатых холстах, поэтому пиксель считается через
    /// масштаб объекта, а не записывается в поле числом.
    ///
    /// Прозрачность контура наследуется от букв: приглушённой строке (<see cref="TextStyle.Muted"/>)
    /// иначе достаётся контур в полную силу, и он перевешивает сами буквы.
    ///
    /// Вешать на светлый текст интерфейса: окна, подсказки, счётчики и имена поверх карты, подписи на
    /// пёстрых значках, надписи над существами. Исключение — мелкий тёмный текст на светлой подложке
    /// (описания в книге заклинаний): там контур не отделяет буквы, а пачкает их.
    /// </summary>
    /// <remarks>
    /// Считает и в режиме правки: иначе в сцене остаётся то, что записано в файл, и надпись в редакторе
    /// выглядит иначе, чем в игре, — расхождение, которого у единого носителя быть не должно.
    /// </remarks>
    [ExecuteAlways]
    [RequireComponent(typeof(Text))]
    [AddComponentMenu("UI/Effects/Text Outline")]
    public class TextOutline : Outline
    {
        private const float SCREEN_PIXELS = 1f;

        protected override void OnEnable()
        {
            base.OnEnable();
            Apply();
        }

        /// <summary>
        /// Холст пересчитал раскладку — вместе с ней мог смениться и его масштаб: он тянется за размером
        /// окна игры. Толщина в единицах объекта тогда обязана поехать в обратную сторону, иначе контур
        /// на экране перестанет быть пикселем.
        /// </summary>
        protected override void OnRectTransformDimensionsChange()
        {
            base.OnRectTransformDimensionsChange();
            Apply();
        }

#if UNITY_EDITOR
        protected override void OnValidate()
        {
            base.OnValidate();
            Apply();
        }
#endif

        /// <summary>
        /// Пересчитать толщину под текущий масштаб. Зовётся сама при включении надписи и смене раскладки;
        /// открыта наружу ради редакторного прохода, приводящего к канону надписи выключенных панелей —
        /// их включения в режиме правки не наступает.
        /// </summary>
        public void Apply()
        {
            float scale = transform.lossyScale.x;

            // Масштаб нулевой — объект схлопнут либо ещё не в холсте: делить не на что, а пересчёт
            // придёт следующим изменением раскладки.
            if (scale <= 0f)
                return;

            float shift = SCREEN_PIXELS / scale;

            effectColor = Color.black;
            effectDistance = new Vector2(shift, -shift);
            useGraphicAlpha = true;
        }
    }
}
