namespace Mmogick
{
    /// <summary>
    /// Оформление текста интерфейса: единственное место, где живут начертания, цвета ролей и отступы
    /// внутри надписи. Собирающему текст (предмет, заклинание, окно сведений) остаётся назвать РОЛЬ
    /// строки — подбирать оформление ему нечем и не нужно.
    ///
    /// Единый носитель нужен потому, что оформление не читается по отдельной надписи: одна и та же роль
    /// стоит в подсказке и в окне сведений, и разъехавшись, они выглядят разными сущностями, хотя
    /// говорят об одном. Теги читает сам Text (rich text).
    ///
    /// Роли разведены НАЧЕРТАНИЕМ и цветом: название жирным, пояснение наклоном, значения цветом денег.
    /// Прозрачностью приглушена одна роль — сведения о виде, а не об этом существе.
    /// </summary>
    public static class TextStyle
    {
        /// <summary>Цвет денег: им же сумма стоит на плашке кошелька и подписаны заголовки окон.</summary>
        private const string MONEY_COLOR = "#FFD700";

        /// <summary>Прозрачность приглушённой строки — см. <see cref="Muted"/>.</summary>
        private const string MUTED_COLOR = "#FFFFFFB3";

        /// <summary>Название предмета, существа, умения — то, о чём идёт речь.</summary>
        public static string Title(string text) { return "<b>" + text + "</b>"; }

        /// <summary>
        /// Пояснение: описание из каталога и тому подобное. Отличается от названия над ним и значений
        /// под ним одним наклоном, полной яркости — спорить с ними за внимание ему нечем и незачем.
        /// </summary>
        public static string Hint(string text) { return "<i>" + text + "</i>"; }

        /// <summary>Строка-значение: цена, стоимость маны, количество.</summary>
        public static string Value(string text) { return "<b><color=" + MONEY_COLOR + ">" + text + "</color></b>"; }

        /// <summary>
        /// Строка о ВИДЕ, а не об этом существе: приглушена, чтобы отличаться от точных сведений. Тот же
        /// белый, что у точных, но вполсилы: текст интерфейса набран светлым по тёмному контуру, и серым
        /// приглушать нельзя — на светлом фоне окна серый потерялся бы вовсе.
        ///
        /// Единственная роль, которой прозрачность отдана, — потому надписи с такими строками обводятся
        /// с наследованием прозрачности, иначе контур останется в полную силу под бледными буквами.
        /// </summary>
        public static string Muted(string text) { return "<color=" + MUTED_COLOR + ">" + text + "</color>"; }

        /// <summary>
        /// Просвет над заголовком блока: полустрока уменьшенным кеглем перед ним. Заголовок обязан
        /// отделяться от предыдущего блока сильнее, чем строки внутри блока — друг от друга, иначе он
        /// теряется в общем потоке. Пробел даём строкой текста, а не отступом объекта: у блока
        /// характеристик заголовок живёт внутри той же надписи, что и её строки, и отодвинуть его
        /// раскладкой нельзя.
        /// </summary>
        public const string HEAD_GAP = "<size=9>\n</size>";
    }
}
