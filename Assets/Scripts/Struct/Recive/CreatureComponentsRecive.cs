using System.Collections.Generic;

#nullable enable

namespace Mmogick
{
	/// <summary>
	/// Компоненты не-игровой сущности — ОБЪЕДИНЕНИЕ полей всех её видов: моба, объекта-сундука, портала,
	/// торговца. Не утверждение, что все они есть у каждого: состав задаёт вид на СЕРВЕРЕ, и чего виду
	/// не положено, то не придёт вовсе — у торговца не будет здоровья, у сундука экипировки. Пришедшее
	/// частично — норма и в другом смысле: дельта несёт только изменившееся, поэтому null значит
	/// «не менялось», а не «пусто».
	///
	/// Почему одна структура на все виды, а не своя на каждый: вид в пакете не едет (он выводится из
	/// префаба), и на разборе выбрать по нему тип нечем — понадобился бы реестр «ключ сущности → вид»
	/// и двухфазный разбор. Разделять имеет смысл, когда наборы видов реально разойдутся.
	///
	/// Появилось новое поле от сервера — это сигнал, что клиент отстал: объяви его здесь осознанно.
	/// Строгую проверку неизвестных полей включает MissingMemberHandling в BaseController.
	/// </summary>
	[System.Serializable]
	public class CreatureComponentsRecive
	{
		/// <summary>
		/// Компоненты пришедшей сущности, какого бы вида она ни была. Единственная точка, знающая про
		/// ЗАТЕНЕНИЕ: <see cref="PlayerRecive"/> объявляет своё поле components заново (new) — более
		/// широким типом, — и у пакета игрока базовое поле остаётся ПУСТЫМ. Чтение через
		/// <see cref="CreatureRecive"/> вернуло бы там null молча, а null у компонентов законен сам по
		/// себе («в этой дельте их нет») — признака ошибки нет, и разъехавшиеся копии этого разбора
		/// расходятся тихо. Потому приведение к типу живёт здесь, а не копией у каждого разбирающего.
		///
		/// null — компонентов в пакете нет либо сущность не существо. Вида, который не был бы ни
		/// игроком, ни существом, в мировом пакете не бывает (<see cref="NewRecive{P, E}"/> объявляет
		/// ровно эти два), поэтому несовпадение типа тут недостижимо и отказом не сигналится.
		/// </summary>
		public static CreatureComponentsRecive? Of(EntityRecive recive)
		{
			if (recive is PlayerRecive player)
				return player.components;

			return (recive as CreatureRecive)?.components;
		}


		/// <summary>
		/// если не приравнять к null - будет  0 при наличии другого лбого элемента класса
		/// </summary>
		public int? hp;
		public int? hp_max;

		public int? mp;
		public int? mp_max;

		public int? speed;

		// Порог бегства — доля максимального здоровья от 0 до 1: опустившись ниже, существо бросает бой
		// и убегает. Компонент положен только хищным видам (враг, зверь), у игрока и объектов его нет
		// вовсе — приходит он всем видящим. Показывает окно сведений о цели.
		public float? flee = null;

		// Радиус зова на помощь в клетках: получив урон, существо поднимает на обидчика сородичей вокруг
		// себя. Виды и рассылка — те же, что у flee.
		public int? assist = null;

		// Добыча трупа (компонент loot) — ПУБЛИЧНЫЙ: приходит ВСЕМ видящим сущность обычной world-дельтой,
		// адресного запроса содержимого нет. Формат слота тот же, что у инвентаря; ёмкость равна числу
		// слотов инвентаря.
		//   null           — поля нет в пакете (no-op, прежнее содержимое в силе);
		//   позиция → null — позиция пуста; все позиции null = добычи нет (не выпало либо обыскан);
		//   позиция → item — предмет.
		// Дельта ЧАСТИЧНА (сервер шлёт per-slot diff) — сливать в накопленное состояние, не подменять
		// его целиком: не пришедшая позиция означает «не менялась», а не «опустела».
		public Dictionary<int, ItemSlotRecive>? loot = null;

		// Экипировка (компонент equip) — ПУБЛИЧНЫЙ компонент: приходит всем, кто видит сущность,
		// потому надетое рисуется и на чужих игроках, и на мобах. Ключ — slug слота экипировки.
		//   null            — поля нет в пакете, no-op (экипировку не трогать);
		//   Count==0        — full-clear (снять всё);
		//   Count>0         — per-key delta (null значение = слот снят, объект = надетый предмет).
		public Dictionary<string, EquipSlotRecive?>? equip = null;

		// Ценник торгующего контейнера (компонент trade) — ПУБЛИЧНЫЙ: приходит всем видящим сущность, в том
		// числе издалека, тогда как её содержимое приватно. Приходит он только тем, кому множители заданы:
		// компонент без значения по умолчанию на сущность не вешается вовсе, а сам ценник разрешён лишь виду
		// торговца. Отличать лавку всё равно по заполненности множителей (TradeRecive.Trades), а не по наличию
		// поля: пустой ценник — законное состояние («не торгует»), и сервер судит по тому же признаку.
		//   null — поля нет в пакете (no-op, прежний ценник в силе).
		public TradeRecive? trade = null;

		// Базовая цена предмета (компонент price) — ПУБЛИЧНЫЙ: приходит вместе с самой сущностью-предметом,
		// лежащей на земле (выброшенная монета, невынесенная добыча). Клиент цену отсюда не берёт — в окнах
		// он считает её по префабу и отличиям экземпляра (AnimationCacheService), — но поле обязано быть
		// объявлено: строгая проверка неизвестных полей роняет разбор всего пакета мира.
		// Дробное: цена приводится к вещественному и у сервера (базовая × множитель торговца).
		public float? price = null;

		// Цвет метки сущности на картах клиента (компонент map_color) — строка HEX «#RRGGBB». Компонент положен
		// ВСЕМ видам и объявлен с умолчанием, потому приходит на каждую сущность, включая своего игрока.
		public string? map_color = null;
	}
}
