namespace Mmogick
{
	/// <summary>
	/// Один занятый слот экипировки сущности (компонент equip). idx — позиция предмета в инвентаре
	/// носителя: по ней владелец держит ярлык на свою ячейку инвентаря. prefab — сам надетый предмет,
	/// по нему строится наложение на скелете; у ЧУЖОЙ сущности инвентарь не приходит вовсе, и prefab —
	/// единственный источник её внешнего вида. null вместо объекта — слот пуст (предмет снят).
	/// </summary>
	[System.Serializable]
	public class EquipSlotRecive
	{
		public int idx;
		public string prefab;
	}
}
