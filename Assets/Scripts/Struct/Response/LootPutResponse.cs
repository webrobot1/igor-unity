#nullable enable

namespace Mmogick
{
    // Положить свой предмет (позиция idx своего инвентаря) в добычу контейнера key (труп);
    // to — желаемая позиция контейнера. Своего инвентаря как ЦЕЛИ команда не знает: перекладка внутри
    // него идёт через InventoryResponse (полный пересейв).
    // Серверная группа — ui/inventory: операции игрока с предметами сервер исполняет по одной за тик,
    // и вклад в контейнер стоит в той же очереди, что пересейв своего инвентаря.
    // Кому принадлежит контейнер, команда не различает: адресат задаётся ключом, а право проверяет
    // сервер (в добычу может положить любой, забрать до истечения срока — только владелец).
    public class LootPutResponse : Response
    {
        public string? key = null;

        public int? idx = null;

        public int? to = null;

        // Сколько единиц позиции отдаём; пусто — позицию целиком. Игрок продаёт часть стака (двадцать
        // шесть яблок торговцу нужны не всегда), и остаток обязан остаться у него.
        public int? count = null;

        public LootPutResponse()
        {
            action = "put";
        }

        public override string group
        {
            get { return "ui/inventory"; }
        }
    }
}
