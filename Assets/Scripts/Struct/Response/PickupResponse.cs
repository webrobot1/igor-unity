#nullable enable

namespace Mmogick
{
    // Подбор лежащей на земле вещи по её ключу. Дальность (radius) сервер от игрока не принимает — свой
    // подбор игрок ведёт вплотную; признак подхода (walk) сервер ставит себе сам при повторе. Клиенту
    // остаётся назвать цель.
    // Вещь дальше дальности — сервер сам подводит к ней персонажа и повторяет подбор до прибытия, поэтому
    // движения к вещи клиент не шлёт вовсе: СВОЯ команда движения игрока подход отменяет.
    public class PickupResponse : Response
    {
        public const string GROUP = "item/pickup";

        // Ключ сущности-вещи. Сервер принимает и список ключей — так за раз берётся несколько вещей
        // (куча монет под ногами), — но клик игрока всегда об одной.
        public string? target = null;

        public override string group
        {
            get { return GROUP; }
        }
    }
}
